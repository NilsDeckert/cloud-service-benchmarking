use rand::{Rng, distr::Alphanumeric, seq::IteratorRandom};
use std::{collections::HashSet, io::{self, Error, ErrorKind}, sync::{Mutex, RwLock}};

/// Probability to execute GET on an existing key
const PROB_GET_KNOWN: f32 = 0.8; 
/// Probability to execute SET on an existing key
const PROB_SET_KNOWN: f32 = 0.15;

#[allow(unused)]
pub struct LoadGenerator {
    key_len_min: u32,
    key_len_max: u32,
    val_len_min: u32,
    val_len_max: u32,
    known_keys: RwLock<HashSet<String>>
}

#[allow(unused)]
impl LoadGenerator {

    /// Validate arguments and return LoadGenerator or Error
    pub fn new(key_len_min: u32, key_len_max: u32, val_len_min: u32, val_len_max: u32) -> io::Result<Self> {
        if key_len_min > key_len_max {
            Err(Error::new(ErrorKind::InvalidInput, "key_len min must be <= max"))
        } else if val_len_min > val_len_max {
            Err(Error::new(ErrorKind::InvalidInput, "val min must be <= max"))
        } else {
            let mut klmin = key_len_min;
            let mut vlmin = val_len_min;

            if key_len_min == 0 {
                klmin = 1;
            }

            if val_len_min == 0 {
                vlmin = 1;
            }

            Ok(Self{
                key_len_min: klmin,
                key_len_max,
                val_len_min: vlmin,
                val_len_max,
                known_keys: RwLock::new(HashSet::new())
            })
        }
    }

    fn generate_random_string(len: u32) -> String {
        rand::rng()
            .sample_iter(&Alphanumeric)
            .take(len as usize)
            .map(char::from)
            .collect()
    }

    pub fn get_key(&self, len: Option<u32>) -> String {
        let mut rng = rand::rng();
        let k_len = if len.is_some() {len.unwrap()} else {rng.random_range(self.key_len_min..self.key_len_max)};
        let key = LoadGenerator::generate_random_string(k_len);

        self.known_keys.write().unwrap().insert(key.clone());

        return key;
    }

    /// Return a random key that previously has been generated by calling get_key
    pub fn get_known_key(&self) -> Option<String> {
        let mut rng = rand::rng();
        self.known_keys.read().unwrap().iter().choose(&mut rng).cloned()
    }

    // Generate a random string with given or random length
    pub fn get_val(&self, len: Option<u32>) -> String {
        let mut rng = rand::rng();
        let v_len = if len.is_some() {len.unwrap()} else {rng.random_range(self.val_len_min..self.val_len_max)};

        LoadGenerator::generate_random_string(v_len)
    }

    pub fn cmd_get(&self) -> redis::Cmd {
        let key: String;
        let r = rand::random::<f32>();
        if r <= PROB_GET_KNOWN {
            key = self.get_known_key().unwrap_or(self.get_key(None));
        } else {
            key = self.get_key(None);
        }

        redis::cmd("GET").arg(key).clone()
    }

    pub fn cmd_set(&self) -> redis::Cmd {
        let key: String;
        let r = rand::random::<f32>();
        if r <= PROB_SET_KNOWN {
            key = self.get_known_key().unwrap_or(self.get_key(None));
        } else {
            key = self.get_key(None);
        }

        let val = self.get_val(None);

        redis::cmd("SET").arg(key).arg(val).clone()

    }
}
