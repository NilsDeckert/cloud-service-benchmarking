/// This load generator implements the key and value lengths
/// described in the following paper:
///
/// [1]  Berk Atikoglu, Yuehai Xu, Eitan Frachtenberg, Song Jiang, and Mike Paleczny. 2012.
/// Workload analysis of a large-scale key-value store.
/// SIGMETRICS Perform. Eval. Rev. 40, 1 (June 2012), 53–64.
/// https://doi.org/10.1145/2318857.2254766

use rand::{Rng, distr::Alphanumeric};

use std::collections::HashSet;
use gevlib::dist::{distutils::{DistQuant, RandomSeed}, gev};

#[allow(unused)]
pub struct EtcLoadGenerator {
    known_keys: HashSet<String>
}

#[allow(unused)]
impl EtcLoadGenerator {

    /// Validate arguments and return LoadGenerator or Error
    pub fn new() -> Self {
        Self{
            known_keys: HashSet::new()
        }
    }

    /// Generate a random string of given length
    fn generate_random_string(len: u32) -> String {
        rand::rng()
            .sample_iter(&Alphanumeric)
            .take(len as usize)
            .map(char::from)
            .collect()
    }

    /// Return a key with the size sampled from a Generalized Extrem Value Distribution
    /// with parameters μ = 30.7984, σ = 8.20449, k = 0.078688.
    ///
    /// See [1]
    pub fn get_key(&mut self) -> String {
        let gev = gev::GEV::new(
            30.7984, // location
            8.20449, // scale
            0.078688 // shape
        );
        let len = gev.random(RandomSeed::default());
        Self::generate_random_string(len as u32)
    }

    /// Return a value with the size sampled from a Generalized Pareto Distribution (GPD)
    /// with parameters θ = 0, σ = 214.476, k = 0.348238.
    ///
    /// See [1]
    pub fn get_val(&self) -> String {
        // Parameters given in the paper for GPD
        let gpd_theta: f64 = 0.;        // Location
        let gpd_sigma: f64 = 214.476;   // Scale
        let gpd_k: f64     = 0.348238;  // Shape

        // Table 5: Probability distribution for first few value lengths
        let discrete_val_len = vec![
            0.00536,
            0.00047,
            0.17820,
            0.09239,
            0.00018,
            0.02740,
            0.00065,
            0.00606,
            0.00023,
            0.00837,
            0.00837,
            0.08989,
            0.00092,
            0.00326,
            0.01980
        ];

        // "The first 15 values of length and probabilities can be modeled separately
        // as a discrete probability distribution"
        let u: f64 = rand::rng().random();
        let mut cum_prob = 0.0;
        for (size, &prob) in discrete_val_len.iter().enumerate() {
            cum_prob += prob;
            if u < cum_prob {
                return Self::generate_random_string(size as u32);
            }
        }

        // Get a fresh random number for the tail distribution
        let v: f64 = rand::rng().random(); 

        // There aren't really packages that provide a generalized pareto distribution,
        // so we'll go with this approach found on wikipedia
        // https://en.wikipedia.org/wiki/Generalized_Pareto_distribution#Generating_GPD_random_variables
        let x = gpd_theta + ((gpd_sigma * ((v.powf(-gpd_k) - 1.)))/gpd_k);

        // The model starts from 15, so the GPD value is the offset FROM 15.
        let final_len = 15.0 + x;

        Self::generate_random_string(final_len as u32)
    }

    /// Return a random key that previously has been generated by calling get_key
    pub fn get_known_key(&self) -> Option<String> {
        return Some(String::from("Hallo"));
    }


    pub fn cmd_get(&mut self) -> redis::Cmd {
        let key: String = self.get_key();
        redis::cmd("GET").arg(key).clone()
    }

    pub fn cmd_set(&mut self) -> redis::Cmd {
        let key: String = self.get_key();
        let val: String = self.get_val();
        redis::cmd("SET").arg(key).arg(val).clone()
    }

    pub fn cmd_del(&mut self) -> redis::Cmd {
        let key: String = self.get_key();
        redis::cmd("DEL").arg(key).clone()
    }
}
