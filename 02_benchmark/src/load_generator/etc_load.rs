use rand::{Rng, distr::Alphanumeric};

// use statrs::distribution::Pareto;
use rand_distr::Pareto;

use std::collections::HashSet;
use gevlib::dist::{distutils::{DistQuant, RandomSeed}, gev};

/// Percentage of GET requests
const ETC_PERC_GET: f32 = 21_000 as f32 / 30_000 as f32;
/// Percentage of SET requests
const ETC_PERC_SET: f32 = 1_500 as f32 / 30_000 as f32;
/// Percentage of DEL requests
const ETC_PERC_DEL: f32 = 7_500 as f32 / 30_000 as f32;

// Make sure our probabilities actualy add up to 1.0
const _: () = assert!(ETC_PERC_GET + ETC_PERC_SET + ETC_PERC_DEL == 1 as f32);

#[allow(unused)]
pub struct EtcLoadGenerator {
    known_keys: HashSet<String>
}

#[allow(unused)]
impl EtcLoadGenerator {

    /// Validate arguments and return LoadGenerator or Error
    pub fn new() -> Self {
        Self{
            known_keys: HashSet::new()
        }
    }

    /// Generate a random string of given length
    fn generate_random_string(len: u32) -> String {
        rand::rng()
            .sample_iter(&Alphanumeric)
            .take(len as usize)
            .map(char::from)
            .collect()
    }

    /// Return a key with the size sampled from a Generalized Extrem Value Distribution
    /// with parameters μ = 30.7984, σ = 8.20449, k = 0.078688.
    ///
    /// See [1]
    pub fn get_key(&mut self) -> String {
        let gev = gev::GEV::new(
            30.7984,
            8.20449,
            0.078688 // TODO: ASSUMING THAT 'k' in the paper means shape
        );
        let len = gev.random(RandomSeed::default());
        Self::generate_random_string(len as u32)
    }

    /// Return a value with the size sampled from a Generalized Pareto Distribution (GPD)
    /// with parameters θ = 0, σ = 214.476, k = 0.348238.
    ///
    /// See [1]
    pub fn get_val(&self) -> String {
        // Parameters given in the paper for GPD
        let gpd_location: f64 = 0.;
        let gpd_scale: f64    = 214.476;
        let gpd_shape: f64    = 0.348238;

        // Table 5: Probability distribution for first few value lengths
        let discrete_val_len = vec![
            0.00536,
            0.00047,
            0.17820,
            0.09239,
            0.00018,
            0.02740,
            0.00065,
            0.00606,
            0.00023,
            0.00837,
            0.00837,
            0.08989,
            0.00092,
            0.00326,
            0.01980
        ];

        // Equivalent parameters for (non-generalized) Pareto Distribution
        // See https://en.wikipedia.org/wiki/Generalized_Pareto_distribution
        let location = gpd_scale / gpd_shape;
        let scale    = 1. / gpd_shape;

        // TODO: Use a cumulative distribution here

        let p = Pareto::new(location, scale).unwrap();
        let mut r = rand::rng();
        let len = r.sample(p);

        Self::generate_random_string(len as u32)
    }

    /// Return a random key that previously has been generated by calling get_key
    pub fn get_known_key(&self) -> Option<String> {
        return Some(String::from("Hallo"));
    }


    pub fn cmd_get(&mut self) -> redis::Cmd {
        let key: String = self.get_key();
        redis::cmd("GET").arg(key).clone()
    }

    pub fn cmd_set(&mut self) -> redis::Cmd {
        let key: String = self.get_key();
        let val: String = self.get_val();
        redis::cmd("SET").arg(key).arg(val).clone()
    }
}
